// Regenerates src/pdf/fonts.generated.ts and src/pdf/brand.generated.ts from assets/:
// MERIDIAN fonts (Montserrat for text, Cinzel for Latin headings; SIL OFL 1.1) as inline @font-face CSS,
// and the logo SVGs from the logobook, so PDF rendering never fetches anything over the network.
// Usage: node scripts/build-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";

const asset = (p) => new URL(`../assets/${p}`, import.meta.url);
const css = readFileSync(asset("fonts/fonts.css.tpl"), "utf8").replace(
  /__([A-Za-z]+-[a-z-]+)__/g,
  (_, name) => `data:font/woff2;base64,${readFileSync(asset(`fonts/${name}.woff2`)).toString("base64")}`,
);
writeFileSync(
  new URL("../src/pdf/fonts.generated.ts", import.meta.url),
  `// Generated by scripts/build-fonts.mjs. Montserrat and Cinzel fonts, SIL Open Font License 1.1.\nexport const FONT_CSS = ${JSON.stringify(css)};\n`,
);

const svg = (name) => readFileSync(asset(`brand/${name}.svg`), "utf8").trim();
writeFileSync(
  new URL("../src/pdf/brand.generated.ts", import.meta.url),
  `// Generated by scripts/build-fonts.mjs from assets/brand (MERIDIAN logobook 2026).\n` +
    `export const LOGO_LOCKUP_NAVY = ${JSON.stringify(svg("lockup-navy"))};\n` +
    `export const LOGO_LOCKUP_WHITE = ${JSON.stringify(svg("lockup-white"))};\n` +
    `export const LOGO_MARK = ${JSON.stringify(svg("mark"))};\n`,
);
