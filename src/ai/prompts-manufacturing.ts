// Prompts for production business ideas. The model finds equipment, market facts and cost inputs with sources;
// every derived number (capacity per month, unit cost, profit, break-even, payback) is computed by our code.
import { DATA_LABELS, SOURCE_TYPES } from "../pdf/exhibition";
import example from "./manufacturing-example.json";
import type { Candidate } from "./prompts";

const CONTEXT = `Ты research-аналитик консалтинговой компании abdulbosit_source. Её клиенты: предприниматели из Узбекистана, которые закупают в Китае производственное оборудование, сырьё и другие товары. Мы готовим для них «идею производственного бизнеса»: конкретная линия из Китая + рынок Узбекистана + предварительная финансовая модель.

Главное правило: ноль выдумок. Каждый факт и каждая цена должны опираться на страницу, которую ты нашёл веб-поиском сейчас. Если не нашёл, честно пиши, что неизвестно. Не придумывай URL: указывай только адреса страниц из результатов поиска. Цена с маркетплейса (Alibaba, Made-in-China и т.п.) это рыночный ориентир, а не подтверждённое коммерческое предложение.`;

export function manufacturingDiscoverPrompt(today: string, topic: string | null, exclude: string[]): string {
  return `${CONTEXT}

Сегодня ${today}. Найди веб-поиском 5–8 конкретных идей производственного бизнеса для Узбекистана на китайском оборудовании.
${topic ? `Тема от владельца: «${topic}». Подбирай идеи под неё.` : "Охвати разные отрасли: упаковка, стройматериалы, пищевое производство, пластик, бумага, металлообработка, текстиль и т.д."}
${exclude.length ? `Уже разобраны, не предлагай повторно: ${exclude.join("; ")}.` : ""}

Критерии: понятный продукт с местным спросом в Узбекистане (стройка, HoReCa, сельское хозяйство, розница); линия доступна малому и среднему бизнесу (примерно до $300 000); у линии есть конкретная модель на сайте производителя или маркетплейсе с характеристиками; сырьё доступно в Узбекистане или легко импортируется.

Ответь ТОЛЬКО JSON-объектом без пояснений (формат общий с поиском выставок, поэтому часть полей пустая):
{"candidates":[{"name":"Qog'oz stakan ishlab chiqarish","edition":"","full_name":"конкретная линия/модель, например «ZBJ-X12 avtomatik qog'oz stakan mashinasi»","city":"O'zbekiston","dates":"","industry":"qadoqlash","official_site":"https://... (сайт производителя или страница объявления)","why":"bir gapda, o'zbek tilida (lotin): nega o'zbek tadbirkoriga qiziq","source_url":"https://... (страница, где ты увидел эту машину и её характеристики)"}]}
Поля name, industry, why пиши на узбекском (латиница). edition и dates оставь пустыми строками, city всегда "O'zbekiston".`;
}

export function manufacturingPrompt(today: string, target: Candidate | string): string {
  const what =
    typeof target === "string"
      ? `Идея (запрос владельца): «${target}».`
      : `Идея: ${target.name}. Линия: ${target.full_name}. Отрасль: ${target.industry}. Страница линии: ${target.source_url || target.official_site}. Почему: ${target.why}`;
  return `${CONTEXT}

Сегодня ${today}. ${what}
Сделай research-пакет для PDF «Ishlab chiqarish g'oyasi: dastlabki biznes model».

Что найти веб-поиском:
1. Оборудование: одна конкретная линия (производитель, модель), цена, производительность в единицах продукта в час, мощность (кВт), площадь, операторы, вес, степень автоматизации, комплектация (included), что ещё нужно докупить (additional_equipment), монтаж, срок поставки, гарантия, сырьё и его спецификация.
2. Фото именно этой машины (image_url): прямая ссылка https на JPG/PNG со страницы производителя или объявления. Только реальное фото этой модели; если прямой ссылки нет, не заполняй поле. Никаких сгенерированных картинок.
3. Рынок Узбекистана: оптовая цена продукта, по которой производитель реально продаёт (selling_price_per_unit, за ту же единицу, что и производительность), при наличии розничная цена (wholesale_price, только для справки), показатели спроса, местные производители и импорт, покупатели, каналы сбыта, риски, ограничения данных.
4. Входные данные модели:
   - capex: линия, доставка Китай → Узбекистан, таможенные платежи и НДС, монтаж/пусконаладка, доп. оборудование, подготовка цеха, оборотные средства;
   - opex_monthly (постоянные в месяц): аренда цеха, зарплата (сколько человек и смен), обслуживание, прочее. Электроэнергию НЕ пиши в opex: укажи production.electricity_price_kwh (тариф для юрлиц в USD за кВт·ч) и equipment.power_kw, наш код посчитает сам;
   - variable_costs (на 1 произведённую единицу): сырьё (в note покажи расход × цену, например «≈ 8,5 g × $1 400/t»), упаковка, краска и т.п. Брак не закладывай: его учитывает наш код через production.scrap_pct;
   - revenue_costs: налог с оборота или другие платежи в % от выручки, если нашёл применимый режим;
   - production: hours_per_day, shifts_per_day, working_days_per_month, utilization_base (обычно 0.6–0.75), scrap_pct; label этих допущений обычно ASSUMPTION.
5. Процесс производства по шагам (process), требования к помещению (facility: площадь, электричество 380 В, вода, газ, вентиляция), риски (risks), что проверить до инвестиций (verify_before_investment), 2–4 тезиса для поста (highlights) и проверенные цифры для поста с источником (post_stats).

Метки (label), строго:
- VERIFIED: значение прочитано на официальной/первичной странице (производитель, госорган, налоговый кодекс).
- MARKET DATA: цена или характеристика с маркетплейса, агрегатора, объявления.
- ESTIMATED: оценка на основе найденных данных (в note поясни, из чего).
- ASSUMPTION: разумное допущение без источника (source: null).
- UNKNOWN: не нашёл; тогда value/amount/pct: null. И наоборот: null только с UNKNOWN.
- CALCULATED не используй: все итоги считает наш код. Не пиши выпуск в месяц, себестоимость, выручку, прибыль, окупаемость, точку безубыточности. Никогда не умножай мощность на цену.
Допустимые метки: ${DATA_LABELS.join(", ")}. Типы источников: ${SOURCE_TYPES.join(", ")}.
Все суммы в USD. Если цена найдена в другой валюте (сум, юань), переведи по текущему курсу и укажи исходную цену и курс в note. Цены за единицу могут быть дробными (0.012).

Правила формата:
- Ответь ТОЛЬКО одним JSON-объектом в формате примера ниже, без пояснений.
- Все тексты для клиента (title, product, highlights, market, note, process, facility, risks, verify_before_investment, value) на узбекском языке, латиница, деловой стиль.
- product.unit: единица продукта на узбекском («dona», «kg», «m²»); capacity_per_hour, selling_price_per_unit и variable_costs в одной и той же единице.
- product.tagline: одна строка, что это за бизнес.
- slug: латиница-цифры-дефис, например "paper-cup-line-2026".
- source во всех полях = id из массива sources, либо null. В sources только реальные страницы из поиска, retrieved_at = ${today}. post_stats только с источником.
- scenarios: [0.5, 0.7, 0.9].
- Не пиши цены и пакеты наших услуг: блок про наши услуги добавляем сами.
- Значения в примере выдуманы для показа формата: никогда не копируй их, ищи свои.

Пример формата:
${JSON.stringify(example)}`;
}
